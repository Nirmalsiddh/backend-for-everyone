import assert from 'node:assert/strict';
import { test } from 'node:test';
import { spawnSync } from 'node:child_process';
import { mkdtemp, readFile, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import pg from 'pg';
import { migrate } from 'drizzle-orm/node-postgres/migrator';
import { buildApp } from '../../src/app.js';
import { createPlatformDatabase } from '../../src/database/platform-db/client.js';
import { PostgresRuntimeRepository } from '../../src/runtime/repository.js';
import { PostgresProjectRepository } from '../../src/modules/projects/repository.js';
import { memoryPlatformAuthRepository } from '../platform-auth-helpers.js';
import { PostgresSchemaRepository } from '../../src/modules/schema-builder/repository.js';
import { CredentialEncryption } from '../../src/security/encryption.js';
import { generateLegacyPlan } from '../../src/modules/schema-builder/plan.js';
import { reconcile } from '../../src/operations/reconciliation.js';
import type { TableRecord } from '../../src/modules/schema-builder/types.js';
import { env } from '../helpers.js';
test('exact b6d1426 v0.8 upgrade retains object identities, receipts, old hashes, FK includes and interrupted operation recovery', async (t) => {
  if (!process.env.V08_SOURCE_DIR || !process.env.TEST_V08_DATABASE_URL) { t.skip('Explicit exact-baseline source and disposable TEST_V08_DATABASE_URL required'); return; }
  const folder = await mkdtemp(join(tmpdir(), 'v09-upgrade-')); t.after(() => rm(folder, { recursive: true, force: true }));
  const output = join(folder, 'fixture.json');
  const prepared = spawnSync(process.execPath, ['--import', 'tsx', 'tests/fixtures/prepare-v08-upgrade.ts'], { cwd: fileURLToPath(new URL('../..', import.meta.url)), env: { ...process.env, V08_FIXTURE_OUTPUT: output }, encoding: 'utf8', timeout: 120000 });
  assert.equal(prepared.status, 0, prepared.stderr);
  const fixture = JSON.parse(await readFile(output, 'utf8'));
  const { db, pool } = createPlatformDatabase(process.env.TEST_V08_DATABASE_URL);
  const customer = new pg.Client({ connectionString: process.env.TEST_CUSTOMER_DATABASE_URL! }); await customer.connect();
  t.after(async () => { await customer.query(`DROP SCHEMA IF EXISTS "${fixture.schema}" CASCADE`); await customer.end(); await pool.end(); });
  await migrate(db, { migrationsFolder: fileURLToPath(new URL('../../migrations', import.meta.url)) });
  const objects = (await customer.query('SELECT c.relname,c.oid::text,obj_description(c.oid,\'pg_class\') AS comment FROM pg_class c JOIN pg_namespace n ON n.oid=c.relnamespace WHERE n.nspname=$1 ORDER BY c.relname', [fixture.schema])).rows;
  assert.deepEqual(objects, fixture.objects);
  for (const golden of fixture.golden) assert.equal(generateLegacyPlan(golden.table as TableRecord, golden.tables).hash, golden.hash);
  const repository = new PostgresSchemaRepository(db);
  const source = await repository.get(fixture.project.id, fixture.owner, fixture.sourceId);
  assert.equal(source.appliedPhysicalRevision, source.appliedRevision); assert.equal(source.indexes!.length, 0);
  assert.ok(!Object.hasOwn(source.appliedDefinition!.definition, 'indexes'));
  assert.equal((await reconcile(db, new CredentialEncryption(env.connectionEncryptionKey), fixture.project.id, fixture.operationId, 'schema', true)).classification, 'POST_STATE');
  const app = buildApp({ env, projectRepository: new PostgresProjectRepository(db), platformAuthRepository: memoryPlatformAuthRepository(fixture.owner), runtimeRepository: new PostgresRuntimeRepository(db), logger: false }); t.after(() => app.close());
  const response = await app.inject({ url: `/api/${fixture.project.slug}/orders/${fixture.order.id}?include=customer_id`, headers: { authorization: 'Bearer ' + fixture.key } });
  assert.equal(response.statusCode, 200, response.body); assert.deepEqual(response.json(), fixture.expanded);
});
